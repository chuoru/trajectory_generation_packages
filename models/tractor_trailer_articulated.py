#!/usr/bin/env python3
##
# @file tractor_trailer_articulated.py
#
# @brief Provide the trailer-centric tractor-trailer articulated model,
# matching the kinematics used by trajectory_generators/
# bspline_tractor_trailer_coverage.py.
#
# Kinematic model (trailer-centric):
#   state = [x_trailer, y_trailer, theta_trailer, gamma]
#   input = [v_tractor, w_tractor]
#
#   xdot     = cos(theta) * [v*cos(gamma) - w*lb*sin(gamma)]
#   ydot     = sin(theta) * [v*cos(gamma) - w*lb*sin(gamma)]
#   thetadot = -v*sin(gamma)/lf - w*lb*cos(gamma)/lf
#   gammadot = thetadot - w
#
# where lb = length_back (tractor rear axle -> hitch) and
#       lf = length_front (hitch -> trailer rear axle).
#
# @note This is a distinct formulation from models/trailer_tractor.py's
# TrailerTractor class (used by trajectory_generators/panoc/
# backward_recovery.py) -- the two ODEs do not match, and mixing them makes
# a simulated plant diverge from a trajectory planned with the other
# formulation. Use this class to track trajectories generated by
# BSplineTractorTrailerCoverage / BSplineEnergyTractorTrailerCoverage.
#
# @section author_doxygen_example Author(s)
# - Created by Tran Viet Thanh on 2026/08/12

# External library
import casadi.casadi as cs


class TractorTrailerArticulated:
    # [x_trailer, y_trailer, theta_trailer, gamma]
    nx = 4

    # [v_tractor, w_tractor]
    nu = 2

    def __init__(self, length_back, length_front):
        """! Constructor.
        @param length_back<float>: lb -- tractor rear axle to hitch [m].
        @param length_front<float>: lf -- hitch to trailer rear axle [m].
        """
        self.length_back = length_back

        self.length_front = length_front

    def function(self, state, input, dt):
        """! Propagate the articulated plant one step forward.
        @param state<list>: [x_trailer, y_trailer, theta_trailer, gamma].
        @param input<list>: [v_tractor, w_tractor].
        @param dt<float>: Time step [s].
        @return<casadi.DM>: Next state.
        """
        theta = state[2]

        gamma = state[3]

        v = input[0]

        w = input[1]

        lb = self.length_back

        lf = self.length_front

        common = v * cs.cos(gamma) - w * lb * cs.sin(gamma)

        dxdt = cs.cos(theta) * common

        dydt = cs.sin(theta) * common

        dthetadt = -v * cs.sin(gamma) / lf - w * lb * cs.cos(gamma) / lf

        dgammadt = dthetadt - w

        dfdt = cs.vertcat(dxdt, dydt, dthetadt, dgammadt)

        next_state = state + dfdt * dt

        return next_state
